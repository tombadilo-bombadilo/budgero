/**
 * Compiles Budgero's user-facing docs (docs/user, English only) into a
 * generated TS module the in-app AI assistant can search via the search_docs
 * tool. Run via `pnpm build:knowledge` (also wired into predev/prebuild).
 * Commit the generated output so builds don't need the docs present.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const docsDir = join(here, '..', '..', '..', 'docs', 'user');
const outDir = join(here, '..', 'src', 'features', 'ai', 'lib', 'knowledge');
const outFile = join(outDir, 'knowledge-base.generated.ts');

/** Parse leading YAML-ish frontmatter (--- ... ---). Returns {data, body}. */
function parseFrontmatter(raw) {
  if (!raw.startsWith('---')) return { data: {}, body: raw };
  const end = raw.indexOf('\n---', 3);
  if (end === -1) return { data: {}, body: raw };
  const fm = raw.slice(3, end).trim();
  const body = raw.slice(end + 4).trim();
  const data = {};
  for (const line of fm.split('\n')) {
    const m = line.match(/^([A-Za-z0-9_]+):\s*(.*)$/);
    if (m) data[m[1]] = m[2].replace(/^["']|["']$/g, '').trim();
  }
  return { data, body };
}

function cleanDocBody(body) {
  return body
    .split('\n')
    .filter((l) => !/^\s*import\s+/.test(l)) // drop MDX import lines
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

function loadDocs() {
  if (!existsSync(docsDir)) return [];
  return readdirSync(docsDir)
    .filter((f) => f.endsWith('.mdx'))
    .map((file) => {
      const raw = readFileSync(join(docsDir, file), 'utf8');
      const { data, body } = parseFrontmatter(raw);
      const id = file.replace(/\.mdx$/, '');
      return {
        id,
        title: data.title || id,
        summary: data.summary || '',
        section: data.section || 'docs',
        body: cleanDocBody(body),
      };
    });
}

const docs = loadDocs();

if (docs.length === 0) {
  // Don't clobber the committed bundle when the docs aren't available
  // (e.g. a Docker build that copies only packages/app).
  console.warn('[build-knowledge] No docs found — keeping existing bundle. Is docs/user present?');
  process.exit(0);
}

mkdirSync(outDir, { recursive: true });
const header = `/* eslint-disable */
// AUTO-GENERATED by scripts/build-knowledge.mjs — do not edit by hand.
// Source: docs/user. Regenerate with: pnpm build:knowledge

export interface KnowledgeDoc {
  id: string;
  title: string;
  summary: string;
  section: string;
  body: string;
}

export const KNOWLEDGE_DOCS: KnowledgeDoc[] = ${JSON.stringify(docs, null, 2)};
`;

// Format with prettier so the output matches what lint-staged commits —
// otherwise every regeneration flips the file between JSON-style and
// prettified quoting and it shows up as perpetually modified.
const { format, resolveConfig } = await import('prettier');
const prettierOptions = (await resolveConfig(outFile)) ?? {};
const formatted = await format(header, { ...prettierOptions, filepath: outFile });

writeFileSync(outFile, formatted, 'utf8');
console.log(`[build-knowledge] Wrote ${docs.length} docs to ${outFile}`);
